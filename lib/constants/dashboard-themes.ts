export function isDashboardThemeInput(theme?: string | null): boolean {
  if (!theme) return false
  return (
    VALID_DASHBOARD_THEMES.includes(theme as DashboardTheme) ||
    Object.prototype.hasOwnProperty.call(LEGACY_DASHBOARD_THEME_ALIASES, theme)
  )
}

export function normalizeDashboardTheme(theme?: string | null): DashboardTheme {
  if (!theme) return DEFAULT_DASHBOARD_THEME
  if (VALID_DASHBOARD_THEMES.includes(theme as DashboardTheme)) {
    return theme as DashboardTheme
  }
  return LEGACY_DASHBOARD_THEME_ALIASES[theme] ?? DEFAULT_DASHBOARD_THEME
}

export function getThemeSwatches(theme: DashboardTheme | string | null | undefined): string[] {
  const palette = THEME_PALETTES[normalizeDashboardTheme(theme)]
  return THEME_SWATCH_KEYS.map((key) => palette[key]).filter(Boolean)
}

